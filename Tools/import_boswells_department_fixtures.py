"""Import twenty visual-only retail fixture masters for Boswell's.

The OBJ source is generated by assets/models/boswells/make_department_fixtures.py.
Every asset name is new; this refuses to overwrite a binary package.
"""

from pathlib import Path
import unreal

ROOT = Path(unreal.Paths.project_dir()) / "assets/models/boswells"
DEST = "/Game/LLK/Boswells/Fixtures"
SIZES = {
    "ShoeDisplay_Long": (180, 580), "ShoeDisplay_Short": (220, 180),
    "ShoeBench_Long": (180, 580), "ShoeBench_Short": (220, 180),
    "BedVignette": (220, 320), "HomeDisplay": (220, 220),
    "FeatureTable": (220, 220), "ToyGondola": (180, 630),
    "SofaVignette": (220, 360), "AppliancePod": (220, 220),
}


def require(ok, why):
    if not ok:
        raise RuntimeError("BOSWELLS_DEPARTMENT_IMPORT " + why)


stems = [(f"SM_BSW_Department_{kind}_{v}", sx, sy)
         for kind, (sx, sy) in SIZES.items() for v in ("A", "B")]
for stem, _, _ in stems:
    require((ROOT / (stem + ".obj")).is_file(), "source missing: " + stem)
    require(not unreal.EditorAssetLibrary.does_asset_exist(DEST + "/" + stem),
            "asset already exists: " + stem)

for stem, sx, sy in stems:
    task = unreal.AssetImportTask()
    task.filename = str(ROOT / (stem + ".obj"))
    task.destination_path = DEST
    task.destination_name = stem
    task.automated = True
    task.replace_existing = False
    task.save = True
    unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks([task])
    mesh = unreal.EditorAssetLibrary.load_asset(DEST + "/" + stem)
    require(isinstance(mesh, unreal.StaticMesh), "mesh missing: " + stem)
    bounds = mesh.get_bounds()
    require(bounds.box_extent.x * 2 <= sx + 0.2 and
            bounds.box_extent.y * 2 <= sy + 0.2 and
            bounds.origin.z - bounds.box_extent.z >= -0.2,
            "imported bounds exceed socket: " + stem)
    slots = mesh.get_editor_property("static_materials")
    require(len(slots) >= 3 and all(
        slot.get_editor_property("material_interface") is not None and
        slot.get_editor_property("material_interface").get_path_name().startswith(
            DEST + "/") for slot in slots),
            "palette slots unresolved: " + stem)
    print("BOSWELLS_DEPARTMENT_IMPORTED", stem,
          f"{bounds.box_extent.x*2:.1f}x{bounds.box_extent.y*2:.1f}x"
          f"{bounds.box_extent.z*2:.1f} cm")
